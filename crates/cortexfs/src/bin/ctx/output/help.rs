pub(crate) fn print_help() -> Result<(), CliError> {
    print_help_lines(&[
        "ctx - CortexFS client",
        "",
        "common:",
        "  ctx help [TOPIC]                   show help (ctx --help is equivalent)",
        "  ctx status                         show mount and runtime status",
        "  ctx agent chat NAME                open the interactive agent chat",
        "  ctx agent send NAME INPUT          send one non-interactive message",
        "  ctx attach [CHANNEL]               attach a visible channel",
        "",
        "sessions:",
        "  ctx                                create a session in the current folder",
        "  ctx resume [AGENT] [--session ID]  resume a session in the current folder",
        "  ctx history AGENT [--session ID]   print durable message history",
        "",
        "more:",
        "  ctx agent ...      agent lifecycle, chat, session, and PTY controls",
        "  ctx terminal ...   terminal resources",
        "  ctx provider ...   provider and secret configuration",
        "  ctx install ...    validate and install extension packages",
        "  ctx update ...     plan or apply a transactional host update",
        "  ctx object ...     install and inspect individual objects",
        "  ctx man TOPIC      full built-in documentation",
        "",
        "important:",
        "  ctx with no arguments is an action, not a help command.",
        "  It mounts the current folder as /workspace; the agent mount policy must allow it.",
        "  If you only want to chat, use: ctx agent chat coder",
        "",
        "defaults:",
        "  agent: coder (override with CTX_DEFAULT_AGENT)",
        "  session: fresh for ctx; current-folder match for ctx resume",
    ])
}

pub(crate) fn print_man(root: &Path, topic: Option<&str>) -> Result<(), CliError> {
    let Some(topic) = topic else {
        return print_shared_or_builtin_man(root, MANUAL_INDEX_FILE, MANUAL_INDEX);
    };
    let Some(manual) = cortexfs_manual(topic) else {
        return Err(CliError::usage(format!(
            "unknown man topic: {topic}; expected agent, tool, model, ctx, root, session, or provider"
        )));
    };
    print_shared_or_builtin_man(root, manual.file_name, manual.content)
}

pub(crate) fn print_shared_or_builtin_man(
    root: &Path,
    file_name: &str,
    fallback: &str,
) -> Result<(), CliError> {
    let shared = cortexfs_paths::shared_path(root, MANUAL_SHARED_DIR)
        .join(if file_name == MANUAL_INDEX_FILE {
            ""
        } else {
            MANUAL_MAN_DIR
        })
        .join(file_name);
    let content = read_file_to_string(&shared).unwrap_or_else(|_error| fallback.to_owned());
    print_terminal_text(ensure_trailing_newline(&content).as_ref())
}

pub(crate) fn ensure_trailing_newline(content: &str) -> Cow<'_, str> {
    if content.ends_with('\n') {
        Cow::Borrowed(content)
    } else {
        Cow::Owned(format!("{content}\n"))
    }
}

